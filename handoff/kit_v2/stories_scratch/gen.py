def hook(text, size=80):
    """first-frame screen hook: top third, y>=330, never spoken; settled on frame 0, lives through scene 1"""
    return {"t": "stamp", "text": text, "at": -0.3, "y": 430, "size": size, "color": "gold", "rot": -0.04, "shake": False}

def stamp(text, at, y=760, size=140, color="red", **k): return {"t": "stamp", "text": text, "at": at, "y": y, "size": size, "color": color, **k}
def icon(name, at, y=760, s=1.2, **k): return {"t": "icon", "name": name, "at": at, "y": y, "s": s, **k}
def counter(text, at, y=780, **k): return {"t": "counter", "text": text, "at": at, "y": y, **k}
def card(label, at, **k): return {"label": label, "at": at, **k}
def cards(items, y=440, **k): return {"t": "cards", "items": items, "y": y, **k}
def pair(a, b, y=470): return {"t": "pair", "items": [a, b], "y": y}
def gauge(label, keys, y=600, **k): return {"t": "gauge", "label": label, "at": keys[0][0], "keys": keys, "y": y, **k}
def note(text, at, color="red", **k): return {"text": text, "at": at, "color": color, **k}
def eq(a, op, b, atA, atOp, atB, y=760, **k): return {"t": "eq", "a": a, "op": op, "b": b, "atA": atA, "atOp": atOp, "atB": atB, "y": y, **k}
def pills(items, at, pos, **k): return {"t": "pills", "items": items, "at": at, "pos": pos, **k}
def sc(lines, fx, hot=None, hotColor=None, tr="push"):
    o = {"lines": lines, "tr": tr, "fx": fx}
    if hot: o["hot"] = {str(k): v for k, v in hot.items()}
    if hotColor: o["hotColor"] = {str(k): v for k, v in hotColor.items()}
    return o
